import logging
import os
import time

import psycopg
from prometheus_client import Counter, start_http_server

from app.config import database_url
from app.logging_config import configure_logging


REPORTS = Counter("worker_reports_total", "Reports generated by the worker.")


def run_once() -> None:
    with psycopg.connect(database_url()) as connection:
        connection.execute(
            "CREATE TABLE IF NOT EXISTS reports("
            "created_at timestamptz DEFAULT now())"
        )
        connection.execute("INSERT INTO reports DEFAULT VALUES")
    REPORTS.inc()


def main() -> None:
    configure_logging("visits-worker")
    interval = int(os.getenv("WORKER_INTERVAL_SECONDS", "30"))
    start_http_server(8001)
    while True:
        try:
            run_once()
            logging.info("report generated")
        except psycopg.Error:
            logging.exception("report generation failed")
        time.sleep(interval)


if __name__ == "__main__":
    main()
